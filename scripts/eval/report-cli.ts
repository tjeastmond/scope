// `bun run eval:report [--check]`: regenerates docs/evaluation-report.md from the committed Jev recording, offline.
// The report is deterministic: the same recording, labels, fixtures and code always render the same bytes.

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { EvalError } from "./freeze.ts";
import { renderReport } from "./report.ts";
import { evaluate } from "./runner.ts";

export const REPO_ROOT = join(import.meta.dir, "../..");
export const REPORT_PATH = "docs/evaluation-report.md";
export const RECORDING_PATH = "eval-recordings/jev-baseline.json";

const NOTE =
  `> Generated by \`bun run eval:report\` from \`${RECORDING_PATH}\`. Do not edit by hand.\n` +
  "> Regenerate after any retrieval, label or Jev-question change, together with a fresh live recording.\n\n";

/** Renders the committed report in memory. The replay path is relative to the current directory (the repo root). */
export async function generateReport(replay: string = RECORDING_PATH): Promise<string> {
  const output = await evaluate({
    modes: ["lexical", "no-jev", "jev"],
    split: "all",
    repeat: 1,
    replay,
    outDir: "unused",
    log: () => {},
  });
  return NOTE + renderReport(output, { deterministic: true });
}

/** Writes `text` to the report, or in check mode compares it with the file on disk without writing. */
export async function applyReport(text: string, options: { check: boolean; reportPath?: string }) {
  const reportPath = options.reportPath ?? REPORT_PATH;
  if (options.check) {
    const current = await readFile(reportPath, "utf8").catch(() => undefined);
    return { upToDate: current === text, written: false };
  }
  await writeFile(reportPath, text);
  return { upToDate: true, written: true };
}

/** Generates the report and writes it, or in check mode compares it with the file on disk. */
export async function reportCommand(options: { check: boolean; reportPath?: string; replay?: string }) {
  return applyReport(await generateReport(options.replay), options);
}

if (import.meta.main) {
  try {
    const { values } = parseArgs({
      args: process.argv.slice(2),
      options: { check: { type: "boolean" } },
      strict: true,
    });
    process.chdir(REPO_ROOT);
    const { upToDate, written } = await reportCommand({ check: values.check === true });
    if (!upToDate) {
      console.error(`${REPORT_PATH} is out of date; run bun run eval:report`);
      process.exitCode = 1;
    } else if (written) console.log(`Wrote ${REPORT_PATH}`);
  } catch (error) {
    if (error instanceof EvalError) console.error(`error: ${error.message}`);
    else console.error(error instanceof Error ? `${error.name}: ${error.message}` : String(error));
    process.exitCode = 1;
  }
}
